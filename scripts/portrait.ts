// Turns assets/avatar.png into ASCII art for the hero card: data/portrait-light.txt and
// data/portrait-dark.txt. The avatar is an illustration on a blue background with a blue
// shirt, so anything blue drops out and only the face, hair and beard remain.
// Light: denser where the image is darker (ink on paper). Dark: denser where it is
// brighter (light on charcoal). Both stretch the subject's own tonal range and add its
// edges, so the glasses, eyes and beard line read clearly. Run again only when the
// avatar changes (`bun run portrait`); the daily build reads the text files.
//
// The committed portraits were generated by Codex (`codex exec -i assets/avatar.png`), not by
// this script, and read better in light mode. Running this script replaces them, so only run it
// as a fallback.
import sharp from "sharp";

const COLS = 172;
const CELL_ASPECT = 0.6; // Geist Mono advance width / line height
const ROWS = Math.round(COLS * CELL_ASPECT);
const RAMP = " .:-=+*#%@";

const SRC = new URL("../assets/avatar.png", import.meta.url).pathname;
const out = (theme: string) => new URL(`../data/portrait-${theme}.txt`, import.meta.url).pathname;

// Sample at 3x per cell so edges can be measured, then average down.
const SS = 3;
const W = COLS * SS;
const H = ROWS * SS;
const { data, info } = await sharp(SRC).resize(W, H, { fit: "fill" }).raw().toBuffer({ resolveWithObject: true });
const ch = info.channels;

const lum = new Float32Array(W * H);
const fg = new Uint8Array(W * H);
for (let i = 0; i < W * H; i++) {
  const r = data[i * ch], g = data[i * ch + 1], b = data[i * ch + 2];
  lum[i] = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  // The subject is warm (skin, brown hair, black outlines); the background and shirt are blue.
  fg[i] = r >= b - 6 ? 1 : 0;
}

// Stretch the subject's luminance between its 2nd and 98th percentiles.
const fgLum = [...lum.filter((_, i) => fg[i])].sort((a, b) => a - b);
const lo = fgLum[Math.floor(fgLum.length * 0.02)];
const hi = fgLum[Math.floor(fgLum.length * 0.98)];
const norm = (v: number) => Math.min(1, Math.max(0, (v - lo) / (hi - lo)));

const at = (x: number, y: number) => lum[Math.min(H - 1, Math.max(0, y)) * W + Math.min(W - 1, Math.max(0, x))];
const edgeAt = (x: number, y: number) => {
  const gx = at(x + 1, y - 1) + 2 * at(x + 1, y) + at(x + 1, y + 1) - at(x - 1, y - 1) - 2 * at(x - 1, y) - at(x - 1, y + 1);
  const gy = at(x - 1, y + 1) + 2 * at(x, y + 1) + at(x + 1, y + 1) - at(x - 1, y - 1) - 2 * at(x, y - 1) - at(x + 1, y - 1);
  return Math.min(1, Math.hypot(gx, gy) * 1.4);
};

function render(theme: "light" | "dark"): string[] {
  const lines: string[] = [];
  for (let row = 0; row < ROWS; row++) {
    let line = "";
    for (let col = 0; col < COLS; col++) {
      let ink = 0, n = 0;
      for (let dy = 0; dy < SS; dy++) {
        for (let dx = 0; dx < SS; dx++) {
          const x = col * SS + dx, y = row * SS + dy, i = y * W + x;
          if (!fg[i]) continue;
          n++;
          const l = norm(lum[i]);
          const tone = theme === "light" ? Math.pow(1 - l, 1.1) : Math.pow(l, 1.3);
          ink += Math.min(1, tone + edgeAt(x, y) * (theme === "light" ? 0.45 : 0.5));
        }
      }
      // Cells mostly outside the subject fade out instead of leaving a hard rim.
      const cover = n / (SS * SS);
      const v = n ? (ink / n) * Math.min(1, cover * 1.6) : 0;
      line += RAMP[Math.min(RAMP.length - 1, Math.floor(v * RAMP.length))];
    }
    lines.push(line.replace(/\s+$/, ""));
  }
  // Drop empty rows at the top so the head sits close to the card's top edge.
  while (lines.length && !lines[0].trim()) lines.shift();
  return lines;
}

for (const theme of ["light", "dark"] as const) {
  const lines = render(theme);
  await Bun.write(out(theme), lines.join("\n") + "\n");
  console.log(`data/portrait-${theme}.txt  ${lines.length} rows`);
}
